            <p class="lead">
              Luana Nanu is a consumer behavior researcher and educator, an
              assistant professor at the University of South Florida, and
              coordinator of the M3 Center for Hospitality Technology and
              Innovation.
            </p>
            <p>
              Her research examines how people perceive, feel, and make
              decisions in service settings. Biophilic design and other
              environmental cues, technology and AI, and media and storytelling
              are complementary areas of her work, with hospitality providing a
              context for understanding consumer behavior.
            </p>
            <p>
              At USF, she teaches hospitality operations, technology, analytics,
              and lodging management. Her education work extends from course
              design and content creation to program development, online
              delivery, and evaluation. She builds learning experiences for
              university students and industry professionals, connecting
              research with practice.
            </p>
