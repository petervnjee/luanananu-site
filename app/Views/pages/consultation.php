            <p class="eyebrow">Working together</p>
            <h2>
              From question <br />
              to useful evidence.
            </h2>
          </div>
          <p class="section-intro">
            The research question or learning need, scope, and outputs are
            agreed around the decision or capability you want to develop.
          </p>
        </div>
        <ol class="process-list">
          <li>
            <div>
              <h3>Frame the question.</h3>
              <p>
                Discuss the situation, the people it affects, the evidence you
                already have, and what a useful answer would change.
              </p>
            </div>
          </li>
          <li>
            <div>
              <h3>Choose the right approach.</h3>
              <p>
                Define the study, curriculum, evidence review, or evaluation.
                Separate what published research shows from what still needs to
                be tested in your context.
              </p>
            </div>
          </li>
          <li>
            <div>
              <h3>Make the findings usable.</h3>
              <p>
                Bring the evidence together in a report, research brief,
                measurement plan, or learning program that supports your next
                step.
              </p>
            </div>
          </li>
